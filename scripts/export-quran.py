"""Export the reader's keyed verses verbatim from the two pinned SQLite sources.

Usage: python scripts/export-quran.py /path/to/databases
No normalization, trimming, spelling conversion, or verse-number insertion is used.
"""
import hashlib
import json
from html.parser import HTMLParser
from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parent.parent
REVISION = 'b519915d1bae271de13dfa06b53a9ea2ae81f851'
SOURCES = {
    'uthmani': ('quran.db', '62460ff86b04d7bf2fcdb3b5493a4d0d15d5b345dc35718281c454afbc1f0da5'),
    'indopak': ('quran_indo.db', 'db482b92208bf45a4b857a25a2386831bf872d7a65380b731c72b57fcb0b1dd3'),
}


class VerseKeys(HTMLParser):
    def __init__(self):
        super().__init__()
        self.keys = {'1:1'}  # The font preview and sidebar basmala.

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'verified-verse' in attrs.get('class', '').split():
            self.keys.add(attrs['data-key'])


def export(directory):
    parser = VerseKeys()
    parser.feed((ROOT / 'public/app-source-v36.html').read_text())
    manifest = {'sourceRevision': REVISION, 'exportedVerses': len(parser.keys), 'sources': {}}
    for script, (filename, expected) in SOURCES.items():
        path = directory / filename
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        assert digest == expected, f'{filename}: unexpected source checksum'
        with sqlite3.connect(f'{path.resolve().as_uri()}?mode=ro', uri=True) as db:
            assert db.execute('PRAGMA integrity_check').fetchone() == ('ok',)
            assert [col[1] for col in db.execute('PRAGMA table_info(verses)')][:3] == ['sura', 'ayah', 'text']
            rows = db.execute('SELECT sura, ayah, text FROM verses ORDER BY sura, ayah').fetchall()
        verses = {f'{sura}:{ayah}': text for sura, ayah, text in rows}
        assert len(rows) == len(verses) == 6236
        assert {sura for sura, ayah, text in rows} == set(range(1, 115))
        for sura in range(1, 115):
            numbers = [ayah for s, ayah, text in rows if s == sura]
            assert numbers == list(range(1, len(numbers) + 1)), f'{filename}: discontinuous surah {sura}'
        assert all(isinstance(text, str) and text.strip() for text in verses.values())
        assert parser.keys <= verses.keys(), f'{filename}: missing reader verse'
        selected = {key: verses[key] for key in sorted(parser.keys, key=lambda k: tuple(map(int, k.split(':'))))}
        payload = json.dumps(selected, ensure_ascii=False, separators=(',', ':'))
        target = ROOT / f'public/data/quran-{script}-v1.js'
        target.write_text(f'// Generated by scripts/export-quran.py; preserve source Unicode exactly.\nwindow.RuqyahQuranSources=window.RuqyahQuranSources||{{}};\nwindow.RuqyahQuranSources.{script}={payload};\n')
        manifest['sources'][script] = {
            'database': filename, 'sha256': digest, 'totalVerses': len(rows), 'totalSurahs': 114,
            'source': f'https://github.com/arowabd-stack/greentech-quran-apk-/blob/{REVISION}/assets/databases/{filename}',
            'payloadSha256': hashlib.sha256(target.read_bytes()).hexdigest(),
        }
        print(f'{script}: checked 6236 verses; exported {len(selected)} reader verses ({target.stat().st_size} bytes)')
    (ROOT / 'public/data/quran-sources.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    export(Path(sys.argv[1]))
